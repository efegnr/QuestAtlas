"""Generate reference outputs of the ORIGINAL Java ATLAS for the Lua tests.

Usage (from the repository root):
    git clone https://github.com/savastakan/atlas  <ATLAS_DIR>
    python tools/reference/generate_expected.py <ATLAS_DIR>

What it does
  1. Writes a few random KISS2 finite state machines to tests/fixtures/fsm/.
  2. Compiles the original Java sources twice:
       * "hashset"  - completely unmodified sources,
       * "treeset"  - Graph.java with HashSet -> TreeSet, i.e. neighbours are
                      iterated in ascending label order (exactly what the Lua
                      Graph does). For bbtas.kiss2.fsm both orders coincide.
  3. Runs RefHarness and writes tests/fixtures/atlas_java_expected.lua.
"""
import os, random, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FSM_DIR = os.path.join(ROOT, "tests", "fixtures", "fsm")
OUT = os.path.join(ROOT, "tests", "fixtures", "atlas_java_expected.lua")
HARNESS = os.path.join(ROOT, "tools", "reference", "RefHarness.java")
SOURCES = ["Atlas.java", "Graph.java", "Edge.java", "Util.java"]

# (name, states, inputs, seed)
RANDOM_FSMS = [
    ("rand_s4_i2", 4, 2, 11), ("rand_s5_i3", 5, 3, 12), ("rand_s6_i2", 6, 2, 13),
    ("rand_s7_i3", 7, 3, 14), ("rand_s8_i4", 8, 4, 15), ("rand_s10_i3", 10, 3, 16),
    ("rand_s12_i2", 12, 2, 17), ("rand_s9_i4", 9, 4, 18),
]


def write_random_fsm(name, states, inputs, seed):
    rnd = random.Random(seed)
    lines = []
    for s in range(states):
        for i in range(inputs):
            lines.append("%d -- %d / %d -> %d" % (s, i, rnd.randrange(inputs), rnd.randrange(states)))
    path = os.path.join(FSM_DIR, name + ".kiss2.fsm")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


def build(atlas_dir, work, variant):
    os.makedirs(work, exist_ok=True)
    for src in SOURCES:
        shutil.copy(os.path.join(atlas_dir, src), work)
    shutil.copy(HARNESS, work)
    if variant == "treeset":
        graph = os.path.join(work, "Graph.java")
        text = open(graph).read().replace("HashSet", "TreeSet")
        open(graph, "w").write(text)
    subprocess.check_call(["javac", "-nowarn", "-d", os.path.join(work, "out")] +
                          [os.path.join(work, f) for f in SOURCES + ["RefHarness.java"]],
                          stderr=subprocess.DEVNULL)
    return os.path.join(work, "out")


def run(classpath, files):
    out = subprocess.check_output(["java", "-cp", classpath, "RefHarness"] + files, text=True)
    result, current = {}, None
    for line in out.splitlines():
        key, _, value = line.partition("=")
        if key == "FILE":
            current = os.path.basename(value)
            result[current] = {}
        else:
            result[current][key] = value
    return result


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    atlas_dir = sys.argv[1]
    os.makedirs(FSM_DIR, exist_ok=True)
    shutil.copy(os.path.join(atlas_dir, "bbtas.kiss2.fsm"), FSM_DIR)
    files = [os.path.join(FSM_DIR, "bbtas.kiss2.fsm")]
    files += [write_random_fsm(*spec) for spec in RANDOM_FSMS]
    with tempfile.TemporaryDirectory() as tmp:
        results = {v: run(build(atlas_dir, os.path.join(tmp, v), v), files) for v in ("hashset", "treeset")}
    with open(OUT, "w", newline="\n") as f:
        f.write("-- AUTO-GENERATED by tools/reference/generate_expected.py - do not edit.\n")
        f.write("-- Output of the ORIGINAL Java ATLAS (github.com/savastakan/atlas).\n")
        f.write("return {\n")
        for variant in ("hashset", "treeset"):
            f.write("    %s = {\n" % variant)
            for name in sorted(results[variant]):
                r = results[variant][name]
                f.write('        ["%s"] = { path = { %s }, suite = "%s" },\n' % (name, r["PATH"], r["SUITE"]))
            f.write("    },\n")
        f.write("}\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
