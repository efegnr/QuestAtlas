-- tests/test_commands.lua - slash commands (Chain of Responsibility) in the simulated client
return function(T, ctx)
    T.suite("Slash commands")

    local Mock = ctx.Mock

    local function run(line)
        Mock.clearChat()
        T.ok(Mock.slash(line), "slash command registered: " .. line)
        return Mock.chatText()
    end

    T.test("chain order: each handler only handles its own words", function()
        local ns = ctx.loadAddon()
        local head, handlers = ns.CommandChainFactory.build()
        local executed = {}
        for _, h in ipairs(handlers) do
            h.execute = function(self) executed[#executed + 1] = self:getPrimaryName() end
        end
        T.ok(head:handle({}, "route", ""))
        T.ok(head:handle({}, "s", ""))
        T.ok(head:handle({}, "", ""))
        T.deepEq(executed, { "route", "strategy", "help" })
        T.ok(head:handle({ print = function() end, t = function() return "" end }, "nonsense", ""),
            "the last link (UnknownCommand) accepts everything")
    end)

    T.test("/qa and /questatlas both work; help lists every command", function()
        ctx.startGame()
        local text = run("/qa help")
        T.contains(text, "Komutlar")
        for _, word in ipairs({ "/qa route", "/qa next", "/qa strategy", "/qa compare", "/qa plan", "/qa lang" }) do
            T.contains(text, word)
        end
        T.contains(run("/questatlas help"), "Komutlar")
        T.contains(run("/qa"), "Komutlar", "no argument = help")
    end)

    T.test("unknown command", function()
        ctx.startGame()
        T.contains(run("/qa dance"), "Bilinmeyen komut")
    end)

    T.test("/qa route and /qa next", function()
        ctx.startGame()
        Mock.acceptQuest(783)
        Mock.advanceTime(1)
        local text = run("/qa route")
        T.contains(text, "Rota (atlas)")
        T.contains(text, "1. Teslim et: A Threat Within @ Marshal McBride (48.9, 41.6)")
        text = run("/qa next")
        T.contains(text, "Marshal McBride")
        T.contains(text, "harita işareti yok", "classic client has no map pins")
    end)

    T.test("/qa next places a map pin when the client supports it", function()
        ctx.startGame({ waypoints = true })
        Mock.acceptQuest(783)
        Mock.advanceTime(1)
        T.contains(run("/qa next"), "haritaya işaretlendi")
        T.eq(Mock.waypoint().uiMapID, 1429)
    end)

    T.test("/qa strategy: set, cycle, reject", function()
        ctx.startGame()
        T.contains(run("/qa strategy nearest"), "Rota stratejisi: nearest")
        T.contains(run("/qa strategy"), "Rota stratejisi: bruteforce", "cycles to the next one")
        T.contains(run("/qa s"), "Rota stratejisi: atlas")
        local text = run("/qa strategy teleport")
        T.contains(text, "Bilinmeyen strateji 'teleport'")
        T.contains(text, "atlas, nearest, bruteforce")
    end)

    T.test("/qa compare prints one line per strategy", function()
        ctx.startGame({ level = 5 })
        Mock.acceptQuest(7)
        Mock.acceptQuest(33)
        Mock.acceptQuest(18)
        Mock.advanceTime(1)
        local text = run("/qa compare")
        T.contains(text, "atlas:")
        T.contains(text, "nearest:")
        T.contains(text, "bruteforce:")
    end)

    T.test("/qa available and /qa plan add|list|remove|clear", function()
        ctx.startGame({ level = 2 })
        local text = run("/qa available")
        T.contains(text, "#783")
        T.notContains(text, "#7 ", "prerequisite missing")
        T.contains(run("/qa plan add 783"), "#783 numaralı görev plana eklendi")
        T.contains(run("/qa plan 33"), "#33 numaralı görev plana eklendi", "shorthand")
        T.contains(run("/qa plan list"), "#783 A Threat Within")
        T.contains(run("/qa plan add 783"), "zaten planda")
        T.contains(run("/qa plan add 7"), "henüz alınamaz")
        T.contains(run("/qa plan add 999999"), "veritabanında yok")
        T.contains(run("/qa plan remove 33"), "plandan çıkarıldı")
        T.contains(run("/qa plan remove 33"), "planda değil")
        T.contains(run("/qa plan clear"), "Plan temizlendi")
        T.contains(run("/qa plan list"), "Planlanan görev yok")
        T.contains(run("/qa plan jump 3"), "/qa plan add/remove")
    end)

    T.test("/qa lang switches the language of chat and window", function()
        ctx.startGame()
        T.contains(run("/qa lang en"), "Language: English")
        T.contains(run("/qa help"), "Commands")
        T.contains(Mock.renderFrame("QuestAtlasFrame"), "Quests (0)")
        T.contains(run("/qa lang tr"), "Dil: Türkçe")
        T.contains(Mock.renderFrame("QuestAtlasFrame"), "Görevler (0)")
        T.contains(run("/qa lang xx"), "/qa lang tr/en")
    end)

    T.test("/qa hide, /qa show, /qa toggle", function()
        ctx.startGame()
        run("/qa hide")
        T.eq(_G.QuestAtlasFrame:IsShown(), false)
        run("/qa show")
        T.eq(_G.QuestAtlasFrame:IsShown(), true)
        run("/qa toggle")
        T.eq(_G.QuestAtlasFrame:IsShown(), false)
        run("/qa ui")
        T.eq(_G.QuestAtlasFrame:IsShown(), true)
    end)

    T.test("/qa refresh", function()
        ctx.startGame()
        T.contains(run("/qa refresh"), "Rota güncellendi")
    end)
end
