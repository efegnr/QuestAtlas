-- tests/test_services.lua - API adapter, repository, factory, geometry, settings
return function(T, ctx)
    T.suite("Services")

    local Mock = ctx.Mock

    for _, flavor in ipairs({ "classic", "modern" }) do
        T.test("WowApiAdapter reads the quest log (" .. flavor .. " API)", function()
            local ns = ctx.loadAddon({ apiFlavor = flavor })
            Mock.acceptQuest(7)
            Mock.acceptQuest(783)
            Mock.setObjectiveProgress(7, 1, 4)
            Mock.acceptQuest(33)
            Mock.completeObjectives(33)
            local api = ns.WowApiAdapter.new(_G)
            T.eq(api:getQuestApiFlavor(), flavor)
            local entries = api:getQuestLogEntries()
            T.eq(#entries, 3, "zone headers are skipped")
            T.eq(entries[1].questID, 7)
            T.eq(entries[1].title, "Kobold Camp Cleanup")
            T.eq(entries[1].objectives[1].text, "Kobold Vermin slain: 4/10")
            T.eq(entries[1].objectives[1].finished, false)
            T.eq(entries[1].isComplete, false)
            T.eq(entries[2].questID, 783)
            T.eq(#entries[2].objectives, 0)
            T.eq(entries[3].isComplete, true)
            T.eq(entries[3].objectives[1].finished, true)
        end)
    end

    T.test("WowApiAdapter: failed quests, completed flag, player info", function()
        local ns = ctx.loadAddon({ level = 5 })
        Mock.acceptQuest(7)
        Mock.failQuest(7)
        Mock.setQuestCompleted(783)
        local api = ns.WowApiAdapter.new(_G)
        T.eq(api:getQuestLogEntries()[1].isFailed, true)
        T.eq(api:isQuestCompleted(783), true)
        T.eq(api:isQuestCompleted(7), false)
        local info = api:getPlayerInfo()
        T.eq(info.level, 5)
        T.eq(info.faction, "Alliance")
    end)

    T.test("WowApiAdapter: position, world coordinates, map names", function()
        local ns = ctx.loadAddon()
        Mock.movePlayer(1429, 42.1, 65.9)
        local api = ns.WowApiAdapter.new(_G)
        local mapID, x, y = api:getPlayerMapPosition()
        T.eq(mapID, 1429)
        T.near(x, 42.1, 1e-9)
        T.near(y, 65.9, 1e-9)
        local continent, wx, wy = api:getWorldPosition(1429, 42.1, 65.9)
        T.eq(continent, 0)
        T.near(wx, -7939.58 - 0.659 * 2314.58, 1e-6, "world X")
        T.near(wy, 1535.42 - 0.421 * 3470.83, 1e-6, "world Y")
        T.eq(api:getMapName(1429), "Elwynn Forest")
        Mock.setInInstance(true)
        T.eq(api:getPlayerMapPosition(), nil, "no position inside instances")
    end)

    T.test("WowApiAdapter: map pins only when the client supports them", function()
        local ns = ctx.loadAddon({ waypoints = false })
        T.eq(ns.WowApiAdapter.new(_G):setWaypoint(1429, 50, 50), false)
        ns = ctx.loadAddon({ waypoints = true })
        T.eq(ns.WowApiAdapter.new(_G):setWaypoint(1429, 50, 40), true)
        local pin = Mock.waypoint()
        T.eq(pin.uiMapID, 1429)
        T.near(pin.position.x, 0.5, 1e-9)
        T.near(pin.position.y, 0.4, 1e-9)
    end)

    T.test("Static and API map geometry agree; the chain falls back to the table", function()
        local ns = ctx.loadAddon()
        local api = ns.WowApiAdapter.new(_G)
        local location = ns.Location.new(1429, 48.9, 41.6)
        local c1, x1, y1 = ns.ApiMapGeometry.new(api):toWorld(location)
        local c2, x2, y2 = ns.StaticMapGeometry.new(ns.MapData):toWorld(location)
        T.eq(c1, c2)
        T.near(x1, x2, 1e-6)
        T.near(y1, y2, 1e-6)
        _G.C_Map.GetWorldPosFromMapPos = nil -- client without the API
        local chain = ns.ChainedMapGeometry.new({ ns.ApiMapGeometry.new(api), ns.StaticMapGeometry.new(ns.MapData) })
        local c3, x3 = chain:toWorld(location)
        T.eq(c3, 0)
        T.near(x3, x2, 1e-6)
    end)

    T.test("DistanceCalculator: yards, same place, other continent, unknown map", function()
        local ns = ctx.loadAddon()
        local calc = ctx.staticDistance(ns)
        local northshire = ns.Location.new(1429, 48.9, 41.6)
        local goldshire = ns.Location.new(1429, 42.1, 65.9)
        local d = calc:distance(northshire, goldshire)
        T.ok(d > 550 and d < 650, "Northshire -> Goldshire is about 600 yards, got " .. d)
        T.eq(calc:distance(northshire, ns.Location.new(1429, 48.9, 41.6)), 0)
        local mockMaps = { [1411] = { name = "Durotar", continent = 1, width = 1, height = 1, left = 0, top = 0 } }
        local twoContinents = ns.DistanceCalculator.new(ns.ChainedMapGeometry.new({
            ns.StaticMapGeometry.new(ns.MapData), ns.StaticMapGeometry.new(mockMaps) }))
        T.eq(twoContinents:distance(northshire, ns.Location.new(1411, 50, 50)), ns.DistanceCalculator.CROSS_CONTINENT_PENALTY)
        T.eq(calc:distance(northshire, ns.Location.new(9999, 50, 50)), ns.DistanceCalculator.UNKNOWN_PENALTY)
    end)

    T.test("QuestRepository: NPC locations and available quests", function()
        local ns = ctx.loadAddon()
        local repo = ns.QuestRepository.new(ns.QuestData)
        local mcbride = repo:getNpcLocation("MARSHAL_MCBRIDE")
        T.eq(mcbride.label, "Marshal McBride")
        T.eq(repo:getNpcLocation("NOBODY"), nil)
        local completed = {}
        local function isCompleted(id) return completed[id] == true end
        local level1 = repo:findAvailable({ level = 1, faction = "Alliance" }, isCompleted, {})
        T.ok(ns.Util.contains(level1, 783), "A Threat Within is available at level 1")
        T.ok(not ns.Util.contains(level1, 7), "Kobold Camp Cleanup needs A Threat Within")
        T.ok(not ns.Util.contains(level1, 15), "level 2 quest not available at level 1")
        completed[783] = true
        local after = repo:findAvailable({ level = 1, faction = "Alliance" }, isCompleted, {})
        T.ok(ns.Util.contains(after, 7), "prerequisite done")
        T.ok(not ns.Util.contains(after, 783), "completed quests are not offered again")
        local horde = repo:findAvailable({ level = 10, faction = "Horde" }, isCompleted, {})
        T.eq(#horde, 0, "Alliance quests are not offered to the Horde")
        local inLog = repo:findAvailable({ level = 1, faction = "Alliance" }, isCompleted, { [7] = true })
        T.ok(not ns.Util.contains(inLog, 7), "quests already in the log are not offered")
    end)

    T.test("QuestRepository: every quest references existing NPCs and valid maps", function()
        local ns = ctx.loadAddon()
        local repo = ns.QuestRepository.new(ns.QuestData)
        for _, id in ipairs(repo:getAllQuestIds()) do
            local q = repo:getQuest(id)
            T.ok(repo:getNpc(q.giver), id .. " giver")
            T.ok(repo:getNpc(q.turnIn), id .. " turn-in")
            T.ok(q.prerequisite == nil or repo:getQuest(q.prerequisite), id .. " prerequisite exists")
            for _, o in ipairs(q.objectives) do
                T.ok(ns.MapData[o.map] and o.x >= 0 and o.x <= 100 and o.y >= 0 and o.y <= 100, id .. " objective")
            end
        end
    end)

    T.test("QuestFactory: statuses from log entries", function()
        local ns = ctx.loadAddon()
        local factory = ns.QuestFactory.new(ns.QuestRepository.new(ns.QuestData))
        local function entry(id, complete, failed, finished)
            local objectives = {}
            for i, f in ipairs(finished) do objectives[i] = { index = i, text = "o" .. i, finished = f } end
            return { questID = id, title = "T" .. id, level = 1, isComplete = complete, isFailed = failed, objectives = objectives }
        end
        T.eq(factory:create("log", entry(7, false, false, { false })).status, ns.QuestStatus.IN_PROGRESS)
        T.eq(factory:create("log", entry(7, false, false, { true })).status, ns.QuestStatus.READY)
        T.eq(factory:create("log", entry(7, true, false, { false })).status, ns.QuestStatus.READY)
        T.eq(factory:create("log", entry(783, false, false, {})).status, ns.QuestStatus.READY, "no objectives")
        T.eq(factory:create("log", entry(7, false, true, { false })).status, ns.QuestStatus.FAILED)
        local q = factory:create("log", entry(7, false, false, { false }))
        T.eq(q.turnIn.label, "Marshal McBride")
        T.ok(q.objectives[1].location ~= nil, "objective location merged from the database")
        local unknown = factory:create("log", entry(90001, false, false, { false }))
        T.eq(unknown.known, false)
        T.eq(unknown:isRoutable(), false)
        local planned = factory:create("planned", 33)
        T.eq(planned.status, ns.QuestStatus.PLANNED)
        T.eq(planned.giver.label, "Eagan Peltskinner")
        T.eq(factory:create("planned", 424242), nil)
        T.raises(function() factory:create("email", {}) end, "unknown quest source kind")
    end)

    T.test("QuestFactory: new creators can be registered (open/closed)", function()
        local ns = ctx.loadAddon()
        local factory = ns.QuestFactory.new(ns.QuestRepository.new(ns.QuestData))
        factory:registerCreator("custom", function(id) return ns.Quest.new({ id = id, title = "custom" }) end)
        T.eq(factory:create("custom", 5).title, "custom")
    end)

    T.test("SettingsStore: defaults, persistence in the SavedVariables table", function()
        local ns = ctx.loadAddon()
        local env = {}
        local store = ns.SettingsStore.new("TestDB", env)
        store:load()
        T.eq(store:get("strategy"), "atlas")
        T.eq(store:get("language"), "trTR")
        store:set("strategy", "nearest")
        T.eq(env.TestDB.strategy, "nearest", "written into the global table")
        local other = ns.SettingsStore.new("TestDB", env)
        other:load()
        T.eq(other:get("strategy"), "nearest", "existing values are kept")
        T.ok(other:get("planned") ~= ns.SettingsStore.DEFAULTS.planned, "defaults are copied, not shared")
    end)
end
